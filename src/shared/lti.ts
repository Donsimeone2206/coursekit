import type { Grade } from './types.js';

/**
 * LTI 1.3 API shapes (Coursekit as the platform that launches external tools). Shared by the server and the web UI.
 */

export type LtiToolStatus = 'active' | 'disabled';

/** The values a tool's administrator copies into the tool. All null until the site's public URL is set. */
export interface LtiPlatformDetails {
  /** False until COURSEKIT_PUBLIC_URL (or the publicUrl option) is set; LTI needs it. */
  configured: boolean;
  issuer: string | null;
  authUrl: string | null;
  tokenUrl: string | null;
  jwksUrl: string | null;
  deepLinkReturnUrl: string | null;
}

export interface LtiTool {
  id: string;
  name: string;
  description: string;
  /** Default launch URL (target_link_uri). */
  toolUrl: string;
  /** OIDC login initiation URL. */
  loginUrl: string;
  redirectUris: string[];
  /** Where the tool's public keys come from. */
  keyType: 'jwks' | 'key';
  jwksUrl: string | null;
  /** PEM or JWK. Public keys only. */
  publicKey: string | null;
  deepLinkingUrl: string | null;
  customParams: Record<string, string>;
  shareName: boolean;
  shareEmail: boolean;
  /** Assignment and Grade Services. */
  allowAgs: boolean;
  /** Names and Role Provisioning Services. */
  allowNrps: boolean;
  status: LtiToolStatus;
  /** Generated by Coursekit. */
  clientId: string;
  deploymentId: string;
  /** External tool activities that use the tool. */
  activityCount: number;
  createdAt: string;
  updatedAt: string;
}

export interface LtiToolList {
  platform: LtiPlatformDetails;
  tools: LtiTool[];
}

export interface LtiToolDetail {
  platform: LtiPlatformDetails;
  tool: LtiTool;
}

/** Body of POST /api/admin/lti/tools and PATCH /api/admin/lti/tools/:id. */
export interface LtiToolInput {
  name: string;
  description?: string;
  toolUrl: string;
  loginUrl: string;
  redirectUris: string[];
  keyType: 'jwks' | 'key';
  jwksUrl?: string | null;
  publicKey?: string | null;
  deepLinkingUrl?: string | null;
  customParams?: Record<string, string>;
  shareName?: boolean;
  shareEmail?: boolean;
  allowAgs?: boolean;
  allowNrps?: boolean;
  status?: LtiToolStatus;
}

/** A tool teachers can pick for an External tool activity. */
export interface LtiToolOption {
  id: string;
  name: string;
  description: string;
  toolUrl: string;
  /** The tool supports content selection (Deep Linking). */
  deepLinking: boolean;
  /** The tool may send grades back. */
  grades: boolean;
  status: LtiToolStatus;
}

/** What the activity page needs to launch an External tool activity. */
export interface LtiLaunchInfo {
  toolName: string | null;
  /** False when the activity can't be launched; `problem` says why. */
  available: boolean;
  problem: string | null;
  presentation: 'window' | 'embed';
  /** Same-origin URLs that start the launch. */
  windowUrl: string;
  embedUrl: string;
  /** The viewer's own grade, for graded activities. */
  grade: Grade | null;
}
